"""High-precision Riemann Xi / xi via Riemann's integral (Decimal, 110 digits).
Ξ(t) = 2∫_0^∞ Φ(u) cos(tu) du,  Φ(u) = 2Σ_n (2π²n⁴e^{9u/2} − 3πn²e^{5u/2}) exp(−πn²e^{2u}).
ξ(s) = Ξ(−i(s−1/2)) = 2∫_0^∞ Φ(u) cosh((s−1/2)u) du.
Trapezoid rule on [0, 3], h = 1/100 (even analytic integrand: spectrally accurate)."""
from decimal import Decimal as D, getcontext
from math import factorial
getcontext().prec = 110

def _arctan_inv(x):
    x = D(x); x2 = x * x; term = 1 / x; s = term; k = 1
    while True:
        term /= -x2; k += 2; t = term / k
        if abs(t) < D(10) ** -118: break
        s += t
    return s
PI = 16 * _arctan_inv(5) - 4 * _arctan_inv(239)

def _exp_i(x):
    two_pi = 2 * PI; x = x - two_pi * int(x / two_pi)
    re, im, tr, ti, k = D(0), D(0), D(1), D(0), 0
    while True:
        re += tr; im += ti; k += 1
        tr, ti = -ti * x / k, tr * x / k
        if abs(tr) + abs(ti) < D(10) ** -118: return re, im

H = D(1) / D(100); UMAX = 300
def Phi(u):
    s = D(0)
    for n in range(1, 13):
        n2 = n * n
        s += (2 * PI * PI * n2 * n2 * (9 * u / 2).exp() - 3 * PI * n2 * (5 * u / 2).exp()) * (-PI * n2 * (2 * u).exp()).exp()
    return 2 * s
NODES = [(j * H, Phi(j * H) * (D(1) / 2 if j == 0 else D(1))) for j in range(UMAX + 1)]

def xi_t_derivs(t, K):
    """[Ξ(t), Ξ'(t), ..., Ξ^(K)(t)] at real Decimal t."""
    t = D(t); out = [D(0)] * (K + 1)
    for u, w in NODES:
        c, s = _exp_i(t * u); uk = D(1)
        for k in range(K + 1):
            out[k] += w * uk * [c, -s, -c, s][k % 4]; uk *= u
    return [2 * H * v for v in out]

def xi_s1_derivs(K):
    """[ξ(1), ξ'(1), ..., ξ^(K)(1)]."""
    out = [D(0)] * (K + 1)
    for u, w in NODES:
        e = (u / 2).exp(); ch, sh = (e + 1 / e) / 2, (e - 1 / e) / 2; uk = D(1)
        for k in range(K + 1):
            out[k] += w * uk * (ch if k % 2 == 0 else sh); uk *= u
    return [2 * H * v for v in out]

def log_taylor(derivs):
    """Taylor coefficients ℓ_m of log F(x+h) − log F(x) from derivatives F^(k)(x)."""
    c = [d / factorial(k) / derivs[0] for k, d in enumerate(derivs)]
    l = [D(0)] * len(c)
    for m in range(1, len(c)):
        l[m] = c[m] - sum((D(j) * l[j] * c[m - j] for j in range(1, m)), D(0)) / D(m)
    return l

def power_sums_at(x, K):
    """p_k(x) = Σ_ρ w_ρ^k, w_ρ = 1/(x − t_ρ)² over all zeros t_ρ of Ξ:  p_k = −2k ℓ_{2k}."""
    l = log_taylor(xi_t_derivs(x, 2 * K))
    return [None] + [-2 * k * l[2 * k] for k in range(1, K + 1)]

